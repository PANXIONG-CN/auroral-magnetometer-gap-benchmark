ROOT = paths.ROOT
RDIR = ROOT / "experiments" / "E011_locked_test" / "results"
TDIR = ROOT / "paper" / "agu_latex" / "tables"


def load_locked(prefix: str) -> tuple[pd.DataFrame, Path]:
    files = sorted(RDIR.glob(f"{prefix}_locked_*.csv"))
    if not files:
        raise FileNotFoundError(f"Missing {prefix}_locked_*.csv in {RDIR}")
    p = files[-1]
    return pd.read_csv(p, dtype={"event": str}), p


def fmt_num(x: float, ndigits: int = 1, signed: bool = False) -> str:
    val = round(float(x), ndigits)
    if abs(val) == 0.0:
        val = 0.0
    if signed:
        s = f"{val:+.{ndigits}f}"
    else:
        s = f"{val:.{ndigits}f}"
    if s.startswith("-"):
        return f"$-${s[1:]}"
    if s.startswith("+"):
        return f"$+${s[1:]}"
    return s


def fmt_ci(lo: float, hi: float, ndigits: int = 1, signed: bool = False) -> str:
    return f"[{fmt_num(lo, ndigits, signed)}, {fmt_num(hi, ndigits, signed)}]"


def fmt_mean_ci(
    mean: float, lo: float, hi: float, ndigits: int = 1, signed: bool = False
) -> str:
    return f"{fmt_num(mean, ndigits, signed)} {fmt_ci(lo, hi, ndigits, signed)}"


def write_tex(name: str, lines: list[str]) -> Path:
    TDIR.mkdir(parents=True, exist_ok=True)
    out = TDIR / name
    out.write_text(
        "% Auto-generated by scripts/export_latex_assets.py from frozen E011 outputs.\n"
        + "\n".join(lines)
        + "\n",
        encoding="utf-8",
    )
    return out


def export_tab1_storms(c2: pd.DataFrame) -> Path:
    ev_cfg = yaml.safe_load((ROOT / "config" / "events.yaml").read_text("utf-8"))
    cand = {c["id"]: c for c in ev_cfg["test_candidates"]}
    near0_secs = c2[(c2["config"] == "near0") & (c2["method"] == "secs")]

    lines = [
        r"\begin{tabular}{@{}llrrr@{}}",
        r"\toprule",
        r"Storm & Window (UTC days) & Dst min (nT) & $Kp \geq 5$ (min) & Scored station-min \\",
        r"\midrule",
    ]
    for e in ev_cfg["test"]:
        eid = e["id"]
        c = cand[eid]
        t0 = pd.Timestamp(e["start"])
        t1 = pd.Timestamp(e["end"]) - pd.Timedelta(days=1)
        win = f"{t0.strftime('%Y-%m-%d')} to {t1.strftime('%m-%d')}"
        dst_min = int(c["dst_min"])
        g = near0_secs[near0_secs["event"] == eid]
        # Each unique scenario_start is a 180-min UTC interval
        kp5_scen = g.drop_duplicates("scenario_start")
        kp5_min = int((kp5_scen["kp_group"] == "Kp>=5").sum() * 180)
        scored = int(g["n_scored"].sum())
        lines.append(
            f"{eid} & {win} & $-${abs(dst_min)} & {kp5_min:,} & {scored:,} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return write_tex("tab1_storms.tex", lines)


def export_tab2_budget_and_c1(
    wf_sum: pd.DataFrame,
    wf_steps: pd.DataFrame,
    c1_paired: pd.DataFrame,
    c1_clean: pd.DataFrame,
    bias: pd.DataFrame,
) -> Path:
    e011_cfg = yaml.safe_load(
        (ROOT / "experiments" / "E011_locked_test" / "config.yaml").read_text("utf-8")
    )
    order = [s["label"] for s in e011_cfg["waterfall"]["steps"]]
    disp_names = {
        "IDW, training median": "IDW, training median",
        "IDW, decomposed": "IDW, decomposed",
        "SECS, decomposed": "SECS, decomposed",
        "SECS + temporal, decomposed": "SECS + Kalman, decomposed",
    }

    dense_s = wf_sum[wf_sum["station_set"] == "dense"].set_index("step")
    sparse_s = wf_sum[wf_sum["station_set"] == "sparse"].set_index("step")
    dense_st = wf_steps[wf_steps["station_set"] == "dense"].set_index("comparison")
    sparse_st = wf_steps[wf_steps["station_set"] == "sparse"].set_index("comparison")

    lines = [
        r"\begin{tabular}{@{}lrlrl@{}}",
        r"\toprule",
        r"Step & Dense & Change [95\% CI] & Sparse & Change [95\% CI] \\",
        r"\midrule",
    ]
    for i, step in enumerate(order):
        d_val = fmt_num(dense_s.loc[step, "rmse_h"], 1)
        s_val = fmt_num(sparse_s.loc[step, "rmse_h"], 1)
        if i == 0:
            d_chg = "---"
            s_chg = "---"
        else:
            key = f"{order[i - 1]} - {step}"
            dr = dense_st.loc[key]
            sr = sparse_st.loc[key]
            # step minus previous: negative means lower error
            d_chg = fmt_mean_ci(-dr["mean"], -dr["hi"], -dr["lo"], 1, signed=True)
            s_chg = fmt_mean_ci(-sr["mean"], -sr["hi"], -sr["lo"], 1, signed=True)
        lines.append(f"{disp_names[step]} & {d_val} & {d_chg} & {s_val} & {s_chg} \\\\")

    lines += [r"\bottomrule", r"\end{tabular}"]
    return write_tex("tab2_budget.tex", lines)


def export_tab2b_station_jumps(bias: pd.DataFrame) -> Path:
    # Stations whose relative bias shift exceeds 60 nT in any storm
    major = ["MUO", "MAS", "IVA", "PEL", "KIR"]
    s2015 = ["20150317", "20150622", "20151220"]
    s2021_24 = ["20211104", "20230323", "20230423", "20240510", "20241010"]

    def summarize_group(df: pd.DataFrame) -> str:
        parts = []
        for comp in ("Y", "X"):
            vals = df[f"relative_{comp}"].to_numpy()
            if max(abs(vals)) < 15.0:
                continue
            vmin, vmax = float(vals.min()), float(vals.max())
            if abs(vmax - vmin) < 10.0:
                m = round(float(vals.mean()))
                parts.append(f"${comp}$: {fmt_num(m, 0, signed=True)}")
            else:
                lo_i, hi_i = round(vmin), round(vmax)
                parts.append(
                    f"${comp}$: {fmt_num(lo_i, 0, signed=True)} to {fmt_num(hi_i, 0, signed=True)}"
                )
        return ", ".join(parts) if parts else "$<15$"

    lines = [
        r"\begin{tabular}{@{}lll@{}}",
        r"\toprule",
        r"Station & 2015 storms (nT) & 2021--2024 storms (nT) \\",
        r"\midrule",
    ]
    for st in major:
        b_st = bias[bias["station"] == st]
        c15 = summarize_group(b_st[b_st["event"].isin(s2015)])
        if st == "IVA":
            b23 = b_st[b_st["event"].isin(["20230323", "20230423", "20240510", "20241010"])]
            c21 = summarize_group(b23) + " (2023--2024)"
        else:
            c21 = summarize_group(b_st[b_st["event"].isin(s2021_24)])
        lines.append(f"{st} & {c15} & {c21} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return write_tex("tab_c1_jumps.tex", lines)


def export_tab3_spatial(
    c2: pd.DataFrame, c2_hull: pd.DataFrame, c2_tests: pd.DataFrame
) -> Path:
    near0 = c2[c2["config"] == "near0"]
    ev_loo = stats.event_summary(near0, by=["event", "method"])

    m_order = [
        ("secs", "SECS"),
        ("idw", "IDW"),
        ("ridge", "Ridge regression"),
        ("nearest", "Nearest neighbour"),
    ]
    lines = [
        r"\begin{tabular}{@{}lcccc@{}}",
        r"\toprule",
        r"Method & $\mathrm{RMSE}_H$ (nT) & Peak err.\ (nT) & $|\Delta t|$ (min) & $dB_H/dt$ (nT/min) \\",
        r"\midrule",
    ]
    for key, label in m_order:
        g = ev_loo[ev_loo["method"] == key]
        b_h = stats.bootstrap_mean(g["rmse_h"].to_numpy())
        b_p = stats.bootstrap_mean(g["peak_err"].to_numpy())
        b_t = stats.bootstrap_mean(g["peak_dt_abs_min"].to_numpy())
        b_d = stats.bootstrap_mean(g["dbdt_rmse"].to_numpy())
        lines.append(
            f"{label} & {fmt_mean_ci(b_h['mean'], b_h['lo'], b_h['hi'], 1)} & "
            f"{fmt_mean_ci(b_p['mean'], b_p['lo'], b_p['hi'], 1)} & "
            f"{fmt_mean_ci(b_t['mean'], b_t['lo'], b_t['hi'], 1)} & "
            f"{fmt_mean_ci(b_d['mean'], b_d['lo'], b_d['hi'], 2)} \\\\"
        )

    lines += [
        r"\midrule",
        r"\multicolumn{5}{@{}l}{\textit{Sparsity and geometry comparisons (comparator minus SECS $\mathrm{RMSE}_H$; $>0$ favors SECS)}} \\",
        r"Comparison & Inside hull (nT) & Outside hull (nT) & Slope (nT / 100 km) & $\geq 200$ km diff.\ (nT) \\",
        r"\midrule",
    ]
    for comp, label in [("idw - secs", "IDW $-$ SECS"), ("ridge - secs", "Ridge $-$ SECS")]:
        h_in = c2_hull[(c2_hull["inside_hull"] == True) & (c2_hull["comparison"] == comp)].iloc[0]
        h_out = c2_hull[(c2_hull["inside_hull"] == False) & (c2_hull["comparison"] == comp)].iloc[0]
        t_row = c2_tests[c2_tests["comparison"] == comp].iloc[0]
        lines.append(
            f"{label} & {fmt_mean_ci(h_in['mean'], h_in['lo'], h_in['hi'], 1)} & "
            f"{fmt_mean_ci(h_out['mean'], h_out['lo'], h_out['hi'], 1)} & "
            f"{fmt_mean_ci(t_row['slope_nT_per_100km'], t_row['slope_lo'], t_row['slope_hi'], 1)} & "
            f"{fmt_mean_ci(t_row['sparse_end_nT'], t_row['sparse_end_lo'], t_row['sparse_end_hi'], 1)} \\\\"
        )

    lines += [r"\bottomrule", r"\end{tabular}"]
    return write_tex("tab3_spatial.tex", lines)


def export_tab4_temporal(c3_gains: pd.DataFrame, c3_offsets: pd.DataFrame) -> Path:
    lines = [
        r"\begin{tabular}{@{}lcccccc@{}}",
        r"\toprule",
        r" & \multicolumn{3}{c}{Dense configuration (nT)} & \multicolumn{3}{c}{Sparse configuration (nT)} \\",
        r"\cmidrule(lr){2-4} \cmidrule(lr){5-7}",
        r"Interval & Persist. & Bias corr. & Kalman & Persist. & Bias corr. & Kalman \\",
        r"\midrule",
        r"\multicolumn{7}{@{}l}{\textit{Complete 180-minute gaps (mean [95\% storm-bootstrap CI])}} \\",
    ]
    for grp, grp_label in [("all", "All minutes"), ("Kp>=5", r"$Kp \geq 5$")]:
        cells = []
        for sset in ("dense", "sparse"):
            for m in ("persistence", "bias_correction", "kalman"):
                r = c3_gains[
                    (c3_gains["kp_group"] == grp)
                    & (c3_gains["station_set"] == sset)
                    & (c3_gains["comparison"] == f"secs - {m}")
                ].iloc[0]
                cells.append(
                    f"\\shortstack{{{fmt_num(r['mean'], 1)}\\\\\\scriptsize {fmt_ci(r['lo'], r['hi'], 1)}}}"
                )
        lines.append(f"{grp_label} & " + " & ".join(cells) + r" \\[4pt]")

    lines += [
        r"\midrule",
        r"\multicolumn{7}{@{}l}{\textit{By elapsed minutes since outage onset (point estimate; $^*$95\% CI excludes zero)}} \\",
    ]
    bins = [
        (0, "0--15 min"),
        (15, "15--30 min"),
        (30, "30--60 min"),
        (60, "60--90 min"),
        (90, "90--120 min"),
        (120, "120--180 min"),
    ]
    for lo_edge, label in bins:
        cells = []
        for sset in ("dense", "sparse"):
            for m in ("persistence", "bias_correction", "kalman"):
                r = c3_offsets[
                    (c3_offsets["station_set"] == sset)
                    & (c3_offsets["offset_lo"] == lo_edge)
                    & (c3_offsets["method"] == m)
                ].iloc[0]
                sig = r["lo"] > 0 or r["hi"] < 0
                mark = "$^*$" if sig else ""
                cells.append(f"{fmt_num(r['gain'], 1)}{mark}")
        lines.append(f"{label} & " + " & ".join(cells) + r" \\")

    lines += [r"\bottomrule", r"\end{tabular}"]
    return write_tex("tab4_temporal.tex", lines)


