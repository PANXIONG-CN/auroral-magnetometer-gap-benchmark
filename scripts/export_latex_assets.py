"""Export publication LaTeX table fragments directly from frozen E011 locked CSVs.

Reads only committed configurations and the one-time locked test outputs in
`experiments/E011_locked_test/results/*_locked_*.csv` without running any new
reconstructions or reading locked raw magnetometer files.

Usage:
    uv run scripts/export_latex_assets.py
"""

from __future__ import annotations

